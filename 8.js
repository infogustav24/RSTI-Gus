let temperatura = 22;

if (temperatura < 10) {
    console.log("Muito frio")
} else if (temperatura >= 10 && temperatura <= 17) {
    console.log("Frio");
} else if (temperatura >= 18 && temperatura <= 25) {
    console.log("Prazeroso")
} else if (temperatura >= 26 && temperatura <= 32) {
    console.log("Quente");
} else {
    console.log("Muito quente")
}